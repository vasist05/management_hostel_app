export const POSTGRES_SCHEMA_PREVIEW = `-- HOSTEL MANAGER V4.1 — PostgreSQL / Supabase Ready DDL
CREATE TABLE buildings (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  code TEXT UNIQUE NOT NULL,
  address TEXT,
  total_floors INT NOT NULL DEFAULT 1
);

CREATE TABLE rooms (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  building_id UUID REFERENCES buildings(id) ON DELETE RESTRICT,
  floor INT NOT NULL,
  room_number TEXT NOT NULL,
  room_type TEXT NOT NULL,
  capacity INT NOT NULL CHECK (capacity > 0),
  default_rent INT NOT NULL,
  UNIQUE(building_id, room_number)
);

CREATE TABLE beds (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  room_id UUID REFERENCES rooms(id) ON DELETE CASCADE,
  label TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('vacant', 'occupied')),
  occupant_student_id UUID UNIQUE -- Enforces 1 student = 1 active bed
);

CREATE TABLE students (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  student_code TEXT UNIQUE NOT NULL,
  full_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  monthly_rent INT NOT NULL,
  security_deposit INT NOT NULL DEFAULT 0,
  deposit_refunded_amount INT NOT NULL DEFAULT 0,
  status TEXT NOT NULL CHECK (status IN ('active', 'vacated')),
  joining_date DATE NOT NULL,
  vacated_date DATE
);

CREATE TABLE rent_ledger (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id UUID REFERENCES students(id),
  billing_month CHAR(7) NOT NULL,
  rent_amount INT NOT NULL,
  paid_amount INT NOT NULL DEFAULT 0,
  balance_amount INT NOT NULL,
  status TEXT NOT NULL,
  UNIQUE(student_id, billing_month)
);

CREATE TABLE payment_transactions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  receipt_no TEXT UNIQUE NOT NULL,
  student_id UUID REFERENCES students(id),
  ledger_id UUID REFERENCES rent_ledger(id),
  amount INT NOT NULL CHECK (amount > 0),
  payment_type TEXT NOT NULL CHECK (payment_type IN ('rent', 'advance', 'deposit')),
  method TEXT NOT NULL,
  paid_on DATE NOT NULL
);`;
